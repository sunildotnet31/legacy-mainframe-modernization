CREATE TABLE BENEFICIARY (
  BENEFICIARY_ID       CHAR(16)         NOT NULL,
  CUSTOMER_ID          CHAR(12)         NOT NULL,
  BENEFICIARY_NAME     CHAR(80)         NOT NULL,
  BANK_IFSC            CHAR(11)         NOT NULL,
  BANK_ACCOUNT_NO      CHAR(24)         NOT NULL,
  BENEFICIARY_STATUS   CHAR(1)          NOT NULL,
  PRIMARY KEY (BENEFICIARY_ID),
  FOREIGN KEY (CUSTOMER_ID) REFERENCES CUSTOMER(CUSTOMER_ID)
);
