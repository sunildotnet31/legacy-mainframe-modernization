CREATE TABLE NOTIFICATION (
  NOTIFICATION_ID      CHAR(20)         NOT NULL,
  CUSTOMER_ID          CHAR(12)         NOT NULL,
  CHANNEL_CODE         CHAR(3)          NOT NULL,
  DESTINATION          CHAR(120)        NOT NULL,
  MESSAGE_TEXT         CHAR(1000)       NOT NULL,
  DELIVERY_STATUS      CHAR(1)          NOT NULL,
  PRIMARY KEY (NOTIFICATION_ID),
  FOREIGN KEY (CUSTOMER_ID) REFERENCES CUSTOMER(CUSTOMER_ID)
);
